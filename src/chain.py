import os
from dotenv import load_dotenv
from langchain_chroma import Chroma
from langchain_huggingface import HuggingFaceEmbeddings
from langchain_groq import ChatGroq
# If using OpenAI instead, uncomment:
# from langchain_openai import ChatOpenAI
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.runnables import RunnablePassthrough
from langchain_core.output_parsers import StrOutputParser

load_dotenv()

DB_DIR = "./chroma_db"

# 1. Load the ChromaDB Vector Store
embedding_model = HuggingFaceEmbeddings(model_name="sentence-transformers/all-MiniLM-L6-v2")
vector_db = Chroma(persist_directory=DB_DIR, embedding_function=embedding_model)

# 2. Retriever: Fetch top 4 most relevant legal chunks
retriever = vector_db.as_retriever(
    search_type="similarity",
    search_kwargs={"k": 4}
)

# 3. LLM Setup (Groq Llama 3.3 70B)
llm = ChatGroq(
    model="openai/gpt-oss-120b",
    temperature=0.1,
    max_tokens=1024
)
# For OpenAI, replace above with:
# llm = ChatOpenAI(model="gpt-4o-mini", temperature=0.1)

# 4. Strict Legal Prompt
prompt = ChatPromptTemplate.from_template("""
You are an expert Indian Legal AI Assistant. Your role is to provide accurate, objective legal information based on Indian Bare Acts and procedural guidelines.

Guidelines:
1. Always state the specific Act name and Section number (e.g., "Under Section 438 of the Code of Criminal Procedure...").
2. Clarify elements like punishment, bailable/non-bailable, or cognizable/non-cognizable status if mentioned in the context.
3. If the context does not contain enough information to answer definitively, state what is known and clarify what is missing.
4. Keep the explanation structured using bullet points where helpful.
5. End every response with a formal legal disclaimer:
   "⚠️ *Disclaimer: This information is generated by an AI assistant for educational/informational purposes only and does not constitute formal legal counsel.*"

Legal Context:
{context}

User Question:
{question}

Structured Legal Analysis:
""")

def format_docs(docs):
    formatted = []
    for doc in docs:
        source = doc.metadata.get("source_document", "Legal Document")
        formatted.append(f"[Document: {source}]\n{doc.page_content}")
    return "\n\n---\n\n".join(formatted)

# 5. Build RAG Chain
rag_chain = (
    {"context": retriever | format_docs, "question": RunnablePassthrough()}
    | prompt
    | llm
    | StrOutputParser()
)